"""Time each voice-loop step without a microphone, using generated speech.

  bench.py tts    time the Pocket TTS model and save a listening sample
  bench.py stt    time the Moonshine model and check its accuracy
  bench.py loop   run whole turns with real Claude replies
"""
import difflib
import logging
import os
import re
import statistics
import sys
import time
import wave

import numpy as np
from pocket_tts import TTSModel

import voice_loop as vl

HERE = os.path.dirname(os.path.abspath(__file__))
SAMPLES = os.path.join(HERE, "samples")
SENTENCES = [
    "The capital of Japan is Tokyo, a city of about fourteen million people.",
    "Try keeping your bedroom cool and dark, and go to bed at the same time each night.",
    "The sky looks blue because air scatters blue light more than red light.",
    "Boil the egg for about seven minutes if you like a soft centre.",
    "Rice and eggs make a quick fried rice, so add soy sauce and spring onions.",
]
QUESTIONS = [
    "What is the capital of Canada?",
    "Give me one tip for staying focused while studying.",
    "Why do leaves change colour in the autumn?",
    "How long does white rice take to cook?",
    "What is a good stretch for a sore lower back?",
    "Who wrote the novel Crime and Punishment?",
    "How far away is the moon from the earth?",
    "What should I eat before going for a morning run?",
]


def line(name, xs):
    xs = sorted(xs)
    print(f"  {name:<34} median {statistics.median(xs):6.3f}s   fastest {xs[0]:6.3f}s   slowest {xs[-1]:6.3f}s", flush=True)


def save_wav(path, audio, rate):
    pcm = (np.clip(audio, -1, 1) * 32767).astype(np.int16)
    with wave.open(path, "wb") as f:
        f.setnchannels(1)
        f.setsampwidth(2)
        f.setframerate(rate)
        f.writeframes(pcm.tobytes())


def generate(model, voice, text):
    t0 = time.perf_counter()
    first, chunks = None, []
    for chunk in model.generate_audio_stream(voice, text):
        if first is None:
            first = time.perf_counter() - t0
        chunks.append(chunk.numpy())
    return first, time.perf_counter() - t0, np.concatenate(chunks)


def bench_tts():
    os.makedirs(SAMPLES, exist_ok=True)
    for language in [vl.TTS_LANGUAGE]:
        t0 = time.perf_counter()
        model = TTSModel.load_model(language=language)
        voice = model.get_state_for_audio_prompt(vl.TTS_VOICE)
        load = time.perf_counter() - t0
        generate(model, voice, "Ready.")
        firsts, speeds, clips = [], [], []
        for text in SENTENCES:
            first, total, audio = generate(model, voice, text)
            firsts.append(first)
            speeds.append(len(audio) / model.sample_rate / total)
            clips.append(audio)
        print(f"\n{language}: load {load:.1f}s, rate {model.sample_rate} Hz")
        line("first audio", firsts)
        print(f"  speed: median {statistics.median(speeds):.2f}x real time, slowest {min(speeds):.2f}x", flush=True)
        save_wav(os.path.join(SAMPLES, f"{language}.wav"), np.concatenate(clips), model.sample_rate)
        del model, voice
    print("\nsamples saved in", SAMPLES)


def speak_all(texts):
    model = TTSModel.load_model(language=vl.TTS_LANGUAGE)
    voice = model.get_state_for_audio_prompt(vl.TTS_VOICE)
    return [generate(model, voice, t)[2] for t in texts], model.sample_rate


def listen(ear, audio, rate):
    """Feed audio at real-time pace, then return (seconds from key release to text, text)."""
    ear.begin()
    step = 1024
    for start in range(0, len(audio), step):
        ear.feed_block(audio[start:start + step].astype(np.float32), rate)
        time.sleep(step / rate)
    t0 = time.perf_counter()
    text = ear.end(tail=0)
    return time.perf_counter() - t0, text


def words(text):
    return re.findall(r"[a-z0-9']+", text.lower())


def word_errors(reference, heard):
    a, b = words(reference), words(heard)
    matched = sum(m.size for m in difflib.SequenceMatcher(None, a, b).get_matching_blocks())
    return 1 - matched / max(1, len(a))


def bench_stt():
    clips, rate = speak_all(SENTENCES)
    print(f"test speech: {sum(len(c) for c in clips) / rate:.1f}s in total, generated by Pocket TTS")
    for arch in [vl.STT_ARCH]:
        t0 = time.perf_counter()
        ear = vl.Ear(arch, mic=False)
        load = time.perf_counter() - t0
        waits, errors = [], []
        for clip, reference in zip(clips, SENTENCES):
            wait, heard = listen(ear, clip, rate)
            waits.append(wait)
            errors.append(word_errors(reference, heard))
        print(f"\n{arch}: load {load:.1f}s")
        line("text ready after release", waits)
        print(f"  words missed: {100 * statistics.mean(errors):.1f}%   last heard: {heard!r}", flush=True)


def bench_loop():
    clips, rate = speak_all(QUESTIONS)
    logging.disable(logging.INFO)
    mouth = vl.Mouth(vl.PocketVoice(), play=False)
    ear = vl.Ear(mic=False)
    brain = vl.Brain()
    t0 = time.perf_counter()
    brain.warm_up()
    print(f"Claude ready in {time.perf_counter() - t0:.2f}s")
    stages = {"transcript": [], "word": [], "sentence": [], "audio": []}
    for clip, question in zip(clips, QUESTIONS):
        wait, heard = listen(ear, clip, rate)
        marks = {"release": time.perf_counter() - wait, "transcript": time.perf_counter()}
        vl.run_turn(brain, mouth, heard, marks, mouth.token, show=False)
        for stage, values in stages.items():
            values.append(marks[stage] - marks["release"])
        print(f"  heard {heard!r}: {marks['audio'] - marks['release']:.2f}s to first audio", flush=True)
    brain.close()
    print("\nseconds after key release (no key tail, no speaker delay):")
    for stage, values in stages.items():
        line(stage, values)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    logging.disable(logging.INFO)
    {"tts": bench_tts, "stt": bench_stt, "loop": bench_loop}[sys.argv[1]]()
